// /api/climate/timers/{1..5}  or  /api/climate/timers/clear
func (s *Server) handleClimateTimer(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		writeError(w, http.StatusMethodNotAllowed, "method not allowed")
		return
	}
	tail := strings.TrimPrefix(r.URL.Path, "/api/climate/timers/")
	if tail == "clear" {
		if err := s.provider.ClearClimateTimers(); err != nil {
			writeError(w, http.StatusBadGateway, err.Error())
			return
		}
		writeJSON(w, http.StatusOK, map[string]bool{"ok": true})
		return
	}
	slot, err := strconv.Atoi(tail)
	if err != nil || slot < 1 || slot > 5 {
		writeError(w, http.StatusBadRequest, "timer slot must be 1..5 or 'clear'")
		return
	}
	var t ClimateTimer
	if err := json.NewDecoder(r.Body).Decode(&t); err != nil {
		writeError(w, http.StatusBadRequest, "invalid request body")
		return
	}
	if err := s.provider.SetClimateTimer(slot, t); err != nil {
		writeError(w, http.StatusBadGateway, err.Error())
		return
	}
	writeJSON(w, http.StatusOK, map[string]bool{"ok": true})
}

