// /api/system/reboot — requires {"confirm":"REBOOT"} body to prevent accidents.
func (s *Server) handleReboot(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		writeError(w, http.StatusMethodNotAllowed, "method not allowed")
		return
	}
	var req struct {
		Confirm string `json:"confirm"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		writeError(w, http.StatusBadRequest, "invalid request body")
		return
	}
	if req.Confirm != "REBOOT" {
		writeError(w, http.StatusBadRequest, "confirmation required: send {\"confirm\":\"REBOOT\"}")
		return
	}
	if err := s.provider.RebootHost(); err != nil {
		writeError(w, http.StatusBadGateway, err.Error())
		return
	}
	writeJSON(w, http.StatusOK, map[string]bool{"ok": true})
}

