// --- WiFi management ---

func validateSSID(ssid string) error {
	if len(ssid) == 0 || len(ssid) > 32 {
		return fmt.Errorf("ssid must be 1..32 chars")
	}
	for _, r := range ssid {
		if r < 0x20 || r == 0x7f {
			return fmt.Errorf("ssid contains control characters")
		}
	}
	return nil
}

func validatePassword(pw string) error {
	if pw == "" {
		return nil
	}
	if len(pw) < 8 || len(pw) > 63 {
		return fmt.Errorf("password must be 8..63 chars (or empty for open networks)")
	}
	return nil
}

